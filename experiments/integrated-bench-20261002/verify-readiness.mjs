import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {HERE,read,sha,jsonSha,write} from './common.mjs';
const root=path.resolve(process.argv[2]);
const approval=read(path.join(HERE,'launch-development.json'));
const pilot=read(path.join(root,'bench-pilot-summary/SUMMARY.json'));
const correctness=read(path.join(root,'bench-correctness/CORRECTNESS.json'));
const build=read(path.join(root,'bench-build/BUILD.json'));
assert.equal(approval.phase,'development');
assert.equal(approval.pilotSummarySha256,sha(fs.readFileSync(path.join(root,'bench-pilot-summary/SUMMARY.json'))));
assert.equal(approval.correctnessSha256,sha(fs.readFileSync(path.join(root,'bench-correctness/CORRECTNESS.json'))));
assert.equal(approval.buildSha256,jsonSha(build));
assert.equal(pilot.status,'PASS');assert.equal(pilot.mayProceedToMain,true);
assert.equal(pilot.runCount,192);assert.equal(pilot.operationalPrediction.maxShardMinutes<=80,true);
assert.equal(correctness.status,'PASS');assert.equal(correctness.fixtures,288);assert.equal(correctness.calls,6912);
assert.equal(jsonSha(pilot.build),jsonSha(build));
assert.equal(approval.independentPilotAuditStatus,approval.independentPilotAudit.status);
assert.equal(approval.independentPilotAudit.witnessAndProvenanceAuditStatus,'PASS');
assert.equal(approval.independentPilotAudit.scheduleComplete,true);
assert.equal(approval.independentPilotAudit.phase,'pilot');
assert.equal(approval.independentPilotAudit.observedRuns,192);
assert.equal(approval.independentPilotAudit.uniqueMatrixInputsVerified,32);
write(path.join(root,'READINESS.json'),{status:'PASS',pilotRun:approval.pilotRun,measurementExpectedRuns:36048,legacyExpectedRuns:288,buildSha256:jsonSha(build),noPrimaryOrEnumeration:true});
console.log('Frozen correctness/pilot/source/schedule gates allow full development measurement.');
